#!/bin/bash
################################################################################
# Oracle SQL_ID Troubleshooting Script
# Purpose: Proactive diagnosis and recommendations for SQL performance issues
# Usage: ./sql_troubleshoot.sh <SQL_ID> [ORACLE_SID]
################################################################################

set -euo pipefail

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Function to print colored output
print_header() {
    echo -e "\n${BLUE}========================================${NC}"
    echo -e "${BLUE}$1${NC}"
    echo -e "${BLUE}========================================${NC}"
}

print_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
print_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
print_error() { echo -e "${RED}[ERROR]${NC} $1"; }
print_info() { echo -e "${BLUE}[INFO]${NC} $1"; }

# Validate input parameters
if [ $# -lt 1 ]; then
    print_error "Usage: $0 <SQL_ID> [ORACLE_SID]"
    exit 1
fi

SQL_ID="$1"
ORACLE_SID="${2:-${ORACLE_SID:-ORCL}}"

export ORACLE_SID
export ORAENV_ASK=NO

# Source Oracle environment
if [ -f /usr/local/bin/oraenv ]; then
    . /usr/local/bin/oraenv > /dev/null 2>&1
elif [ -f /opt/oracle/product/*/bin/oraenv ]; then
    . $(find /opt/oracle/product -name oraenv | head -1) > /dev/null 2>&1
else
    print_error "Oracle environment script not found"
    exit 1
fi

print_header "Oracle SQL_ID Troubleshooting Report"
echo "SQL_ID: $SQL_ID"
echo "ORACLE_SID: $ORACLE_SID"
echo "Timestamp: $(date '+%Y-%m-%d %H:%M:%S')"
echo "Generated by: $(whoami)@$(hostname)"

################################################################################
# Function: Execute SQL query
################################################################################
execute_sql() {
    local query="$1"
    sqlplus -S / as sysdba <<EOF
SET PAGESIZE 1000
SET LINESIZE 200
SET FEEDBACK OFF
SET HEADING ON
SET VERIFY OFF
$query
EXIT;
EOF
}

################################################################################
# 1. SQL Text and Basic Information
################################################################################
print_header "1. SQL Text and Basic Information"
execute_sql "
SELECT sql_id, sql_text, parsing_schema_name, executions, 
       elapsed_time/1000000 elapsed_sec, cpu_time/1000000 cpu_sec,
       buffer_gets, disk_reads, rows_processed
FROM v\$sql
WHERE sql_id = '$SQL_ID';
"

################################################################################
# 2. Execution Plan
################################################################################
print_header "2. Current Execution Plan"
execute_sql "
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('$SQL_ID', NULL, 'ALLSTATS LAST'));
"

################################################################################
# 3. SQL Statistics History
################################################################################
print_header "3. SQL Performance History (Last 7 Days)"
execute_sql "
SELECT TO_CHAR(s.end_interval_time, 'YYYY-MM-DD HH24:MI') snap_time,
       t.executions_delta executions,
       ROUND(t.elapsed_time_delta/1000000, 2) elapsed_sec,
       ROUND(t.cpu_time_delta/1000000, 2) cpu_sec,
       t.buffer_gets_delta buffer_gets,
       t.disk_reads_delta disk_reads,
       t.rows_processed_delta rows_processed
FROM dba_hist_sqlstat t,
     dba_hist_snapshot s
WHERE t.sql_id = '$SQL_ID'
  AND t.snap_id = s.snap_id
  AND s.end_interval_time >= SYSDATE - 7
ORDER BY s.end_interval_time DESC;
"

################################################################################
# 4. Wait Events Analysis
################################################################################
print_header "4. Wait Events for SQL_ID"
execute_sql "
SELECT event, total_waits, time_waited_micro/1000000 time_waited_sec
FROM v\$sql_monitor
WHERE sql_id = '$SQL_ID'
  AND event IS NOT NULL
ORDER BY time_waited_micro DESC;
"

################################################################################
# 5. Session Information (if currently executing)
################################################################################
print_header "5. Active Session Information"
execute_sql "
SELECT s.sid, s.serial#, s.username, s.status, s.machine, s.program,
       s.sql_id, s.event, s.wait_class, s.seconds_in_wait
FROM v\$session s
WHERE s.sql_id = '$SQL_ID'
  AND s.status = 'ACTIVE';
"

################################################################################
# 6. Object Statistics (Tables/Indexes involved)
################################################################################
print_header "6. Object Statistics for Tables in SQL"
execute_sql "
SELECT o.owner, o.object_name, o.object_type, 
       t.num_rows, t.last_analyzed,
       ROUND((t.blocks * 8192)/1024/1024, 2) size_mb
FROM dba_objects o
LEFT JOIN dba_tables t ON o.owner = t.owner AND o.object_name = t.table_name
WHERE o.object_id IN (
    SELECT object_id 
    FROM v\$sql_plan 
    WHERE sql_id = '$SQL_ID' 
      AND object_id IS NOT NULL
)
AND o.object_type = 'TABLE';
"

################################################################################
# 7. Index Statistics
################################################################################
print_header "7. Index Statistics for Indexes in SQL"
execute_sql "
SELECT o.owner, o.object_name, i.table_name, i.uniqueness,
       i.num_rows, i.distinct_keys, i.clustering_factor, i.last_analyzed
FROM dba_objects o
JOIN dba_indexes i ON o.owner = i.owner AND o.object_name = i.index_name
WHERE o.object_id IN (
    SELECT object_id 
    FROM v\$sql_plan 
    WHERE sql_id = '$SQL_ID' 
      AND object_id IS NOT NULL
)
AND o.object_type = 'INDEX';
"

################################################################################
# 8. SQL Bind Variables
################################################################################
print_header "8. Bind Variables"
execute_sql "
SELECT name, position, datatype_string, value_string
FROM v\$sql_bind_capture
WHERE sql_id = '$SQL_ID'
ORDER BY position;
"

################################################################################
# 9. SQL Profile/Baseline Information
################################################################################
print_header "9. SQL Tuning Artifacts (Profiles/Baselines)"
execute_sql "
SELECT sql_handle, plan_name, enabled, accepted, fixed, 
       TO_CHAR(created, 'YYYY-MM-DD HH24:MI:SS') created
FROM dba_sql_plan_baselines
WHERE signature IN (
    SELECT exact_matching_signature 
    FROM v\$sql 
    WHERE sql_id = '$SQL_ID'
);
"

################################################################################
# 10. Automated Recommendations
################################################################################
print_header "10. AUTOMATED RECOMMENDATIONS"

# Analyze execution statistics
STATS=$(execute_sql "SELECT executions, buffer_gets, disk_reads, rows_processed FROM v\$sql WHERE sql_id = '$SQL_ID' AND ROWNUM = 1;" | tail -2 | head -1)

EXECUTIONS=$(echo $STATS | awk '{print $1}')
BUFFER_GETS=$(echo $STATS | awk '{print $2}')
DISK_READS=$(echo $STATS | awk '{print $3}')
ROWS_PROCESSED=$(echo $STATS | awk '{print $4}')

echo ""
print_info "Performance Analysis:"

# Check for high buffer gets
if [ "$BUFFER_GETS" -gt 100000 ]; then
    print_warning "High buffer gets detected ($BUFFER_GETS)"
    echo "  Recommendation: Review execution plan for full table scans or missing indexes"
fi

# Check for high disk reads
if [ "$DISK_READS" -gt 10000 ]; then
    print_warning "High disk reads detected ($DISK_READS)"
    echo "  Recommendation: Consider increasing buffer cache or optimizing query"
fi

# Check execution count
if [ "$EXECUTIONS" -gt 1000 ]; then
    print_info "Frequently executed query ($EXECUTIONS times)"
    echo "  Recommendation: Ensure optimal execution plan and consider result caching"
fi

echo ""
print_info "Suggested Actions:"
echo "1. Review execution plan in Section 2 for inefficient operations (TABLE ACCESS FULL, NESTED LOOPS with large datasets)"
echo "2. Check object statistics in Sections 6-7 - ensure tables/indexes are analyzed recently"
echo "3. Analyze wait events in Section 4 - high wait times indicate resource contention"
echo "4. Review performance trends in Section 3 - sudden degradation may indicate data growth or plan changes"
echo "5. If consistent issues, consider SQL tuning advisor:"
echo "   - exec DBMS_SQLTUNE.CREATE_TUNING_TASK(sql_id => '$SQL_ID');"
echo "6. For gathering more detailed statistics:"
echo "   - ALTER SESSION SET STATISTICS_LEVEL = ALL;"
echo "   - Execute the SQL and re-check plan with DBMS_XPLAN"

print_header "Report Complete"
print_success "Troubleshooting report generated successfully!"

exit 0
